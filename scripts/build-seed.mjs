// Turns data/starter.mjs into data/catalog.json (used when Supabase isn't connected)
// and supabase/seed.sql (loads the same catalog into Supabase).
// Run with: npm run seed
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { COLLECTIONS, COUNTRIES, DIRECTORS, FILMS } from "../data/starter.mjs";

const slugify = (s) =>
  s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

// Stable ids, so re-running the seed updates rows instead of duplicating them.
const uuid = (key) => {
  const h = createHash("sha1").update("bcd:" + key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const people = new Map();
const person = (name) => {
  const slug = slugify(name);
  if (!people.has(slug)) {
    const d = DIRECTORS[name];
    people.set(slug, { id: uuid("person:" + slug), slug, name, bio: d?.bio ?? null, country: d?.c ?? null, photo_url: null, tmdb_id: null });
  }
  return people.get(slug);
};

const errors = [];
const films = [];
const credits = [];
const filmSlugs = new Set();
const collectionSlugs = new Set(COLLECTIONS.map((c) => c.slug));

for (const f of FILMS) {
  let slug = slugify(f.t);
  if (filmSlugs.has(slug)) slug = `${slug}-${f.y}`;
  filmSlugs.add(slug);
  const id = uuid("film:" + slug);
  for (const c of f.c) if (!COUNTRIES[c]) errors.push(`${f.t}: unknown country ${c}`);
  for (const c of f.col ?? []) if (!collectionSlugs.has(c)) errors.push(`${f.t}: unknown collection ${c}`);
  for (const d of f.d) if (!DIRECTORS[d]) errors.push(`${f.t}: director ${d} has no entry in DIRECTORS`);

  films.push({
    id, slug, title: f.t, original_title: f.ot ?? null, year: f.y, type: f.type,
    countries: f.c, languages: f.l, genres: f.g ?? [], runtime: null, synopsis: f.s,
    poster_url: null, backdrop_url: null, trailer_url: null,
    awards: (f.aw ?? []).map((a) => {
      const [award, category, result, year] = a.split("|");
      if (!["won", "nominated"].includes(result)) errors.push(`${f.t}: award result must be won or nominated`);
      return { award, category, result, year: Number(year) };
    }),
    watch: [], tmdb_id: null, status: "published", featured: Boolean(f.f),
  });

  let order = 0;
  const add = (name, role, character = null) =>
    credits.push({ film_id: id, person_id: person(name).id, role, character, sort: order++ });
  for (const d of f.d) add(d, "director");
  for (const [role, who] of Object.entries(f.crew ?? {})) for (const n of [who].flat()) add(n, role);
  for (const c of f.cast ?? []) {
    const [name, character] = c.split(" as ");
    add(name.trim(), "cast", character?.trim() ?? null);
  }
}

const collections = COLLECTIONS.map((c, i) => ({
  id: uuid("collection:" + c.slug), slug: c.slug, title: c.title, description: c.d, kind: c.kind,
  featured: Boolean(c.f), sort_order: i,
}));
const collectionFilms = [];
for (const [i, f] of FILMS.entries()) {
  for (const c of f.col ?? []) {
    collectionFilms.push({ collection_id: uuid("collection:" + c), film_id: films[i].id, sort: f.y });
  }
}

if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const catalog = {
  films, people: [...people.values()], credits, collections, collection_films: collectionFilms, articles: [],
};
writeFileSync(new URL("../data/catalog.json", import.meta.url), JSON.stringify(catalog, null, 1) + "\n");

// SQL --------------------------------------------------------------------------
const JSON_COLUMNS = new Set(["awards", "watch"]);
const q = (v, col) => {
  if (v === null || v === undefined) return "null";
  if (JSON_COLUMNS.has(col)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table, rows, cols, conflict, update = true) => {
  if (!rows.length) return "";
  const values = rows.map((r) => `(${cols.map((c) => q(r[c], c)).join(", ")})`).join(",\n");
  const set = update ? cols.filter((c) => !conflict.split(",").map((s) => s.trim()).includes(c)).map((c) => `${c} = excluded.${c}`).join(", ") : "";
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do ${update && set ? `update set ${set}` : "nothing"};\n\n`;
};

const fixArray = (sql) => sql.replace(/array\[\]::text\[\]/g, "'{}'::text[]");

let sql = `-- Starter catalog: ${films.length} films, ${people.size} people, ${collections.length} collections.
-- Generated by scripts/build-seed.mjs from data/starter.mjs. Safe to run again.
-- Run after schema.sql. Rows you've edited in the admin keep their posters, trailers and links.

`;
sql += insert("people", catalog.people, ["id", "slug", "name", "bio", "country"], "id");
// Re-running the seed refreshes catalog facts but never wipes posters, trailers or links added since.
sql += insert("films", films, ["id", "slug", "title", "original_title", "year", "type", "countries", "languages", "genres", "synopsis", "awards", "status", "featured"], "id");
sql += insert("credits", credits, ["film_id", "person_id", "role", "character", "sort"], "film_id, person_id, role", false);
sql += insert("collections", collections, ["id", "slug", "title", "description", "kind", "featured", "sort_order"], "id");
sql += insert("collection_films", collectionFilms, ["collection_id", "film_id", "sort"], "collection_id, film_id", false);
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), fixArray(sql));

console.log(`Wrote ${films.length} films, ${people.size} people (${Object.keys(DIRECTORS).length} directors), ${credits.length} credits, ${collections.length} collections.`);

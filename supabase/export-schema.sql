-- Prints the live database's structure as one SQL script: the baseline in supabase/migrations.
-- Run it in the SQL editor (or psql) and save the output; it reads the catalogue and changes nothing.
-- Covers the app's schemas (public, private, pheelm_private, pheelm_email): tables, sequences,
-- functions, constraints, indexes, views, triggers (including those on auth.users), row-level
-- security and policies, grants, storage buckets and policies, and scheduled jobs. Secrets stay in
-- the vault and are only referenced by name.
with recursive
s(n) as (values ('public'), ('private'), ('pheelm_private'), ('pheelm_email')),
rel as (
  select c.oid, c.relname, c.relkind, n.nspname, format('%I.%I', n.nspname, c.relname) q
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (select n from s)
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
parts(k, body) as (
  -- 0. Session, schemas, extensions.
  select '00', 'set check_function_bodies = false;' || chr(10) || 'set search_path = public, extensions;'
  union all
  select '01:' || n, format('create schema if not exists %I;', n) from s where n <> 'public'
  union all
  select '02:' || e.extname, format('create extension if not exists %I with schema %I;', e.extname, en.nspname)
  from pg_extension e join pg_namespace en on en.oid = e.extnamespace
  where e.extname not in ('plpgsql')
  union all
  -- 1. Sequences that aren't identity columns.
  select '10:' || r.q, format('create sequence if not exists %s as %s start %s increment %s;', r.q, format_type(sq.seqtypid, null), sq.seqstart, sq.seqincrement)
  from rel r join pg_sequence sq on sq.seqrelid = r.oid
  where r.relkind = 'S' and not exists (select 1 from pg_depend d where d.objid = r.oid and d.deptype = 'i')
  union all
  -- 2. Tables: columns, defaults, identity, generated, not null.
  select '20:' || r.q, format(E'create table if not exists %s (\n%s\n);', r.q, coalesce((
    select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
      case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
      case when a.attgenerated = 's' then format(' generated always as (%s) stored', pg_get_expr(ad.adbin, ad.adrelid))
           when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
      case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
    from pg_attribute a left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped), ''))
  from rel r where r.relkind in ('r', 'p')
  union all
  -- 3. Functions (bodies aren't checked yet, so their order doesn't matter).
  select '30:' || p.oid::regprocedure::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname in (select n from s) and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  -- 4. Constraints: keys and checks first, then foreign keys.
  select case when co.contype = 'f' then '41:' else '40:' end || r.q || ':' || co.conname,
    format('alter table %s add constraint %I %s;', r.q, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join rel r on r.oid = co.conrelid
  where co.contype in ('p', 'u', 'c', 'f', 'x') and r.relkind in ('r', 'p')
  union all
  -- 5. Indexes that don't back a constraint.
  select '50:' || ir.q, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join rel ir on ir.oid = i.indexrelid join rel tr on tr.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
  union all
  -- 6. Views.
  select '60:' || r.q, format(E'create or replace view %s%s as\n%s', r.q,
    coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', ''), pg_get_viewdef(r.oid, true))
  from rel r join pg_class c on c.oid = r.oid where r.relkind = 'v'
  union all
  -- 7. Triggers, on the app's tables and on auth.users / storage.objects.
  select '70:' || t.tgrelid::regclass::text || ':' || t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  join pg_proc fp on fp.oid = t.tgfoid join pg_namespace fn on fn.oid = fp.pronamespace
  where not t.tgisinternal and (n.nspname in (select n from s) or (n.nspname in ('auth', 'storage') and fn.nspname in (select n from s)))
  union all
  -- 8. Row-level security and policies.
  select '80:' || r.q, format('alter table %s enable row level security;', r.q) || case when c.relforcerowsecurity then format(E'\nalter table %s force row level security;', r.q) else '' end
  from rel r join pg_class c on c.oid = r.oid where c.relrowsecurity
  union all
  select '81:' || po.polrelid::regclass::text || ':' || po.polname,
    format('create policy %I on %s as %s for %s to %s%s%s;', po.polname, po.polrelid::regclass,
      case when po.polpermissive then 'permissive' else 'restrictive' end,
      case po.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
      coalesce((select string_agg(case when ro = 0 then 'public' else quote_ident(rolname) end, ', ') from unnest(po.polroles) ro left join pg_roles on pg_roles.oid = ro), 'public'),
      coalesce(' using (' || pg_get_expr(po.polqual, po.polrelid) || ')', ''),
      coalesce(' with check (' || pg_get_expr(po.polwithcheck, po.polrelid) || ')', ''))
  from pg_policy po join pg_class c on c.oid = po.polrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (select n from s) or n.nspname = 'storage'
  union all
  -- 9. Grants to the API roles: what's revoked matters as much as what's granted.
  select '90:' || r.q, format('revoke all on table %s from public, anon, authenticated;', r.q) || coalesce((
    select string_agg(format(E'\ngrant %s on table %s to %s;', x.privs, r.q, x.who), '')
    from (select case when a.grantee = 0 then 'public' else quote_ident(g.rolname) end who, string_agg(lower(a.privilege_type), ', ' order by a.privilege_type) privs
          from aclexplode(c.relacl) a left join pg_roles g on g.oid = a.grantee
          where a.grantee = 0 or g.rolname in ('anon', 'authenticated', 'service_role')
          group by 1) x), '')
  from rel r join pg_class c on c.oid = r.oid where r.relkind in ('r', 'p', 'v')
  union all
  select '91:' || p.oid::regprocedure::text,
    format('revoke all on function %s from public, anon, authenticated;', p.oid::regprocedure) || case
      when p.proacl is null then format(E'\ngrant execute on function %s to public;', p.oid::regprocedure)
      else coalesce((select string_agg(format(E'\ngrant execute on function %s to %s;', p.oid::regprocedure, case when a.grantee = 0 then 'public' else quote_ident(g.rolname) end), '')
        from aclexplode(p.proacl) a left join pg_roles g on g.oid = a.grantee
        where a.privilege_type = 'EXECUTE' and (a.grantee = 0 or g.rolname in ('anon', 'authenticated', 'service_role'))), '') end
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname in (select n from s) and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select '92:' || n.nspname, format('revoke all on schema %I from public, anon, authenticated;', n.nspname) || coalesce((
    select string_agg(format(E'\ngrant %s on schema %I to %s;', lower(a.privilege_type), n.nspname, quote_ident(g.rolname)), '')
    from aclexplode(n.nspacl) a join pg_roles g on g.oid = a.grantee where g.rolname in ('anon', 'authenticated', 'service_role')), '')
  from pg_namespace n where n.nspname in (select n from s) and n.nspname <> 'public'
  union all
  -- 10. Storage buckets (their policies are with the others above).
  select '95:' || b.id, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
    b.id, b.name, b.public::text, coalesce(b.file_size_limit::text, 'null'), coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
  from storage.buckets b
  union all
  -- 11. Scheduled jobs.
  select '99:' || j.jobname, format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command)
  from cron.job j
)
select string_agg(body, E'\n\n' order by k) from parts
